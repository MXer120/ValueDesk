/**
 * Extract the ABIs this package binds from the Foundry build and write the committed copies:
 *
 *   abi/ValuescanCopyTrading.abi.json   the UUPS implementation's ABI (what the PROXY exposes); plain JSON
 *   abi/TimelockController.abi.json     OpenZeppelin 5.7.0 TimelockController (the recommended owner, spec §10.2)
 *   src/abi.ts                          both, `as const`, for typed use in TypeScript
 *
 * Source: contracts/out (run `forge build` in contracts/ first). The implementation artifact is required; there is no
 * fallback to the interface any more. Nothing here touches the network.
 *
 *   npx tsx tools/extract-abi.ts           write the files
 *   npx tsx tools/extract-abi.ts --check   exit 1 if a committed file differs from the build
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const PACKAGE_DIR = join(here, '..');
export const REPO_DIR = join(PACKAGE_DIR, '..', '..');
export const CONTRACTS_OUT = join(REPO_DIR, 'contracts', 'out');

interface Target {
  /** Export name in src/abi.ts. */
  exportName: string;
  artifact: string;
  jsonOut: string;
}

export const TARGETS: readonly Target[] = [
  {
    exportName: 'valuescanCopyTradingAbi',
    artifact: join(CONTRACTS_OUT, 'ValuescanCopyTrading.sol', 'ValuescanCopyTrading.json'),
    jsonOut: join(PACKAGE_DIR, 'abi', 'ValuescanCopyTrading.abi.json'),
  },
  {
    exportName: 'timelockControllerAbi',
    artifact: join(CONTRACTS_OUT, 'TimelockController.sol', 'TimelockController.json'),
    jsonOut: join(PACKAGE_DIR, 'abi', 'TimelockController.abi.json'),
  },
];
export const ABI_TS_OUT = join(PACKAGE_DIR, 'src', 'abi.ts');

type Item = { type: string; name?: string; [k: string]: unknown };

interface Loaded {
  target: Target;
  abi: Item[];
  compiler: string;
}

const rel = (p: string): string => relative(REPO_DIR, p).split('\\').join('/');

export function loadAbis(): Loaded[] {
  return TARGETS.map((target) => {
    if (!existsSync(target.artifact)) throw new Error(`${rel(target.artifact)} not found: run forge build in contracts/`);
    const j = JSON.parse(readFileSync(target.artifact, 'utf8')) as { abi: Item[]; rawMetadata?: string };
    const compiler = j.rawMetadata ? (JSON.parse(j.rawMetadata) as { compiler: { version: string } }).compiler.version : '?';
    return { target, abi: j.abi, compiler };
  });
}

export const renderAbiJson = (abi: Item[]): string => JSON.stringify(abi, null, 2) + '\n';

export function renderAbiTs(loaded: readonly Loaded[]): string {
  const lines = [
    '// GENERATED by tools/extract-abi.ts. Do not edit by hand: run `npm run abi` in packages/copy-contract after',
    '// `forge build` in contracts/. The same ABIs are committed as abi/*.abi.json.',
    '',
  ];
  for (const l of loaded) {
    lines.push(`// Source: ${rel(l.target.artifact)} (solc ${l.compiler}).`);
  }
  lines.push('');
  lines.push(
    `export const ABI_SOURCES = ${JSON.stringify(
      Object.fromEntries(loaded.map((l) => [l.target.exportName, { artifact: rel(l.target.artifact), compiler: l.compiler }])),
    )} as const;`,
  );
  for (const l of loaded) {
    lines.push('');
    lines.push(`export const ${l.target.exportName} = ${JSON.stringify(l.abi, null, 2)} as const;`);
  }
  lines.push('');
  return lines.join('\n');
}

function main(): void {
  const check = process.argv.includes('--check');
  const loaded = loadAbis();
  const outputs: Array<[string, string]> = [
    ...loaded.map((l): [string, string] => [l.target.jsonOut, renderAbiJson(l.abi)]),
    [ABI_TS_OUT, renderAbiTs(loaded)],
  ];
  if (check) {
    const stale = outputs.filter(([p, c]) => !existsSync(p) || readFileSync(p, 'utf8').replace(/\r\n/g, '\n') !== c);
    if (stale.length) {
      console.error(`stale: ${stale.map(([p]) => relative(PACKAGE_DIR, p)).join(', ')} (run npm run abi)`);
      process.exit(1);
    }
    console.log(`ABIs up to date (${loaded.map((l) => `${l.target.exportName}: ${l.abi.length} items`).join(', ')})`);
    return;
  }
  for (const [p, c] of outputs) writeFileSync(p, c);
  console.log(`wrote ${outputs.map(([p]) => relative(PACKAGE_DIR, p)).join(', ')}`);
}

if (process.argv[1] && resolve(fileURLToPath(import.meta.url)) === resolve(process.argv[1])) main();
