/** Energy as SoDEX writes it: 129.35K, 1.50M, 400.00K. */
export const energy = (n: number): string => {
  const a = Math.max(0, n);
  if (a >= 1e9) return localize(`${(a / 1e9).toFixed(2)}B`);
  if (a >= 1e6) return localize(`${(a / 1e6).toFixed(2)}M`);
  if (a >= 1e3) return localize(`${(a / 1e3).toFixed(2)}K`);
  return localize(String(Math.round(a)));
};

const short = (a: string) => (a.length <= 12 || a.includes('...') || a.includes('…') ? a : `${a.slice(0, 6)}…${a.slice(-4)}`);

