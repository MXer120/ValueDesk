type Which = 'built' | 'joined';

/** The wallet's squad names (public) and members (its sign-in), read once per wallet; `bump` reads them again. */
function useSquadData(v: PointsView): { names: SquadNames | null; members: SquadMembers | null; bump: () => void; setNames: (n: SquadNames) => void } {
  const address = v.mine && !v.sample ? v.c.address : null;
  const [names, setNames] = useState<SquadNames | null>(null);
  const [members, setMembers] = useState<SquadMembers | null>(null);
  const [n, setN] = useState(0);
  useEffect(() => {
    if (!address) { setNames(null); setMembers(null); return; }
    let live = true;
    void fetchSquadNames(address).then((x) => { if (live) setNames(x); }).catch(() => undefined);
    void fetchSquadMembers(address).then((x) => { if (live) setMembers(x); }).catch(() => undefined);
    return () => { live = false; };
  }, [address, n]);
  return { names, members, bump: () => setN((x) => x + 1), setNames };
}

export function Squads({ v }: { v: PointsView }) {
  const cfg = v.c.boost;
  const q = v.squad;
  const d = useSquadData(v);
  const [open, setOpen] = useState<Which | null>(null);
  const [share, setShare] = useState<Which | null>(null);
  const [naming, setNaming] = useState(false);
  // SoDEX's own fallbacks: "Unnamed squad" for the one you built, "Squad I joined" for the other.
  const names: Record<Which, string> = { built: d.names?.built ?? 'Unnamed squad', joined: d.names?.joined ?? 'Squad you joined' };
  const joinedAny = (d.members?.joined.total ?? 0) > 0 || (q?.joined.volume ?? 0) > 0 || !!d.names?.joined;
  const canName = !!d.names && d.names.canSet && !d.names.alreadySet && !d.names.built;
  return (
    <section className="sx-sec spx-box spq" aria-label="Squads">
      <header className="sx-sec__h">
        <div><h2>{v.mine ? 'Your squads' : 'Squad boost'}</h2><p>Up to {cfg ? plusPct(cfg.maxTotalBonusPct) : DASH} on every point: the squad you joined plus the one you built.</p></div>
      </header>
      {!cfg ? <Skeleton className="spx-ladderskel" /> : !v.mine || !q ? (
        v.mine && v.s.loading ? <Skeleton className="spx-ladderskel" /> : <SquadBlock name="SoDEX’s squad steps" cfg={cfg} volume={null} pct={0} />
      ) : (
        <div className="spq-list">
          <SquadBlock
            name={names.built} named={!!d.names?.built} cfg={cfg} volume={q.built.volume} pct={q.built.pct}
            members={d.members?.built.total ?? q.built.members} onOpen={() => setOpen('built')} onShare={() => setShare('built')}
            onName={canName ? () => setNaming(true) : undefined}
          />
          {joinedAny
            ? <SquadBlock name={names.joined} named={!!d.names?.joined} cfg={cfg} volume={q.joined.volume} pct={q.joined.pct} members={d.members?.joined.total} onOpen={() => setOpen('joined')} onShare={() => setShare('joined')} />
            : <JoinSquad v={v} />}
        </div>
      )}
      {open && q && cfg && <SquadInfo v={v} which={open} name={names[open]} cfg={cfg} list={d.members?.[open] ?? null} onClose={() => setOpen(null)} onShare={() => { setOpen(null); setShare(open); }} />}
      {share && v.mine && <SquadShare v={v} which={share} name={names[share]} onClose={() => setShare(null)} />}
      {naming && v.c.address && <NameSquad address={v.c.address} onClose={() => setNaming(false)} onDone={(name) => { if (d.names) d.setNames({ ...d.names, built: name, canSet: false, alreadySet: true }); d.bump(); }} />}
    </section>
  );
}

/** SoDEX's block: name and members pill, the energy chip, what the next step needs, and the milestone track. */
function SquadBlock({ name, named = true, cfg, volume, pct, members, onOpen, onShare, onName }: {
  name: string; named?: boolean; cfg: BoostConfig; volume: number | null; pct: number; members?: number;
  onOpen?: () => void; onShare?: () => void; onName?: () => void;
}) {
  const steps = stepsOf(cfg);
  const t = steps.map((x) => Number(x.threshold));
  const vol = volume ?? 0;
  const reached = t.filter((x) => vol >= x).length;
  const lo = reached === 0 ? 0 : t[reached - 1]!;
  const hi = t[reached] ?? lo;
  const inside = reached >= t.length ? 0 : (vol - lo) / Math.max(1, hi - lo);
  // Equal spacing per step (SoDEX's): the fill runs inside the step it is in, the knob rides its end.
  const fill = Math.min(100, ((reached + Math.max(0, Math.min(1, inside))) / t.length) * 100);
  const nxt = steps[reached] ?? null;
  return (
    <div className="spq-block">
      <div className="spq-block__h">
        <b className={`spq-block__name${named ? '' : ' is-unnamed'}`}>{name}</b>
        {onName && <button type="button" className="spq-name" onClick={onName}><Icon name="pen" size={13} />Name it</button>}
        {onOpen && (
          <button type="button" className="spq-pill" onClick={onOpen} aria-haspopup="dialog">
            {members !== undefined ? `${pts(members)} ${members === 1 ? 'member' : 'members'}` : 'Details'}<Icon name="arrowRight" size={12} />
          </button>
        )}
        <span className="spq-block__end">
          {pct > 0 && <span className="spq-boost">{plusPct(pct)}</span>}
          {onShare && <button type="button" className="spq-share" onClick={onShare} aria-label={`Share ${name}`} title="Share"><Icon name="share" size={18} /></button>}
        </span>
      </div>
      {volume !== null && (
        <div className="spq-block__e">
          <span className="spq-chip"><Bolt size={14} /><b className="sx-num">{energy(vol)}</b><span>Squad Energy</span><EnergyInfo window={cfg.windowRounds} /></span>
          <span className="spq-next">{nxt ? <>Earn <Bolt size={12} /><b className="sx-num">{energy(Number(nxt.threshold) - vol)}</b> more to reach <em>{plusPct(nxt.bonusPct)}</em></> : <>Top step reached</>}</span>
        </div>
      )}
      <div className="spq-track" role="img" aria-label={volume === null ? `Squad steps: ${steps.map((s) => `${plusPct(s.bonusPct)} at ${energy(Number(s.threshold))}`).join(', ')}` : `${name}: ${energy(vol)} energy, ${pct ? plusPct(pct) : 'no boost yet'}`}>
        <div className="spq-track__bar">
          <i style={{ width: `${volume === null ? 0 : fill}%` }} />
          {volume !== null && vol > 0 && <span className="spq-knob" style={{ left: `${fill}%` }}><Bolt size={12} /></span>}
          {steps.map((s, i) => <span key={s.threshold} className={`spq-dot${i < reached ? ' is-on' : i === reached && volume !== null ? ' is-next' : ''}`} style={{ left: `${((i + 1) / steps.length) * 100}%` }} />)}
        </div>
        <ol className="spq-steps">
          {steps.map((s, i) => (
            <li key={s.threshold} className={i < reached ? 'is-on' : i === reached && volume !== null ? 'is-next' : undefined} style={{ '--at': `${((i + 1) / steps.length) * 100}%` } as CSSProperties}>
              <b>{plusPct(s.bonusPct)}</b><small className="sx-num">{energy(Number(s.threshold))}</small>
            </li>
          ))}
        </ol>
      </div>
    </div>
  );
}

/**
 * No squad joined: a captain's code is looked up here (whose squad, its name; SoDEX's public reads), and joined on
 * SoDEX's own page: binding a code is SoDEX's step, once, and it cannot be changed after.
 */
function JoinSquad({ v }: { v: PointsView }) {
  const [code, setCode] = useState('');
  const [found, setFound] = useState<{ code: string; captain: string; name: string | null } | null | 'none' | 'busy'>(null);
  const own = useOwnCode(v.c.address);
  const look = async (e: FormEvent) => {
    e.preventDefault();
    const c = codeOf(code);
    if (c.length < 4) return;
    if (own.state === 'ok' && own.code === c) { setFound('none'); return; }
    setFound('busy');
    const r = await squadOfCode(c).catch(() => null);
    setFound(r ? { code: c, ...r } : 'none');
  };
  const f = found && typeof found === 'object' ? found : null;
  return (
    <div className="spq-block is-join">
      <div className="spq-block__h"><b className="spq-block__name">Join a squad</b><StatusPill size="sm" tone="neutral">Once</StatusPill></div>
      <p className="spq-empty">You joined no squad. On SoDEX you join one with its captain’s invite code: every point you earn then counts toward its boost, and its boost lifts your points.</p>
      <form className="spq-join" onSubmit={(e) => void look(e)}>
        <label className="spq-join__in">
          <span className="sr-only">Invite code</span>
          <input value={code} onChange={(e) => { setCode(codeOf(e.target.value)); setFound(null); }} placeholder="Invite code" autoComplete="off" spellCheck={false} maxLength={18} />
        </label>
        <button type="submit" className="rf-cta spq-join__go" disabled={codeOf(code).length < 4 || found === 'busy'}>{found === 'busy' ? 'Looking…' : 'Find squad'}</button>
      </form>
      {found === 'none' && <p className="spq-join__msg neg" role="alert">SoDEX knows no squad for this code{own.state === 'ok' && own.code === codeOf(code) ? ': it is your own' : ''}.</p>}
      {f && (
        <div className="spq-join__found">
          <span className="spq-join__sq"><b>{f.name ?? `${f.code}’s squad`}</b><small>Captain {short(f.captain)}</small></span>
          <a className="rf-cta spq-join__go" href={referralUrl(f.code)} target="_blank" rel="noopener noreferrer">Join on SoDEX<Icon name="arrowRight" size={13} /></a>
          <small className="spq-join__fine">SoDEX binds the code to your wallet once; it cannot be changed after. The boost starts once you have deposited and traded.</small>
        </div>
      )}
    </div>
  );
}

/** Naming the squad the wallet built, as SoDEX does it: a name, then a confirm, once. */
function NameSquad({ address, onClose, onDone }: { address: string; onClose: () => void; onDone: (name: string) => void }) {
  const [raw, setRaw] = useState('');
  const [step, setStep] = useState<'edit' | 'confirm' | 'done'>('edit');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const c = checkSquadName(raw);
  const count = Array.from(raw.trim().replace(/\s+/g, ' ')).length;
  const confirm = async () => {
    if (!c.ok) return;
    setBusy(true); setError(null);
    try {
      const name = await nameSquad(address, c.name);
      setStep('done');
      onDone(name);
    } catch (e) {
      setError(nameError(e));
      setStep('edit');
    } finally {
      setBusy(false);
    }
  };
  const foot = step === 'edit'
    ? <div className="spq-dlg__foot"><button type="button" className="dlg-btn" onClick={onClose}>Cancel</button><button type="button" className="dlg-btn is-go" disabled={!c.ok} onClick={() => setStep('confirm')}>Next</button></div>
    : step === 'confirm'
      ? <div className="spq-dlg__foot"><button type="button" className="dlg-btn" disabled={busy} onClick={() => setStep('edit')}>Edit</button><button type="button" className="dlg-btn is-go" disabled={busy} aria-busy={busy || undefined} onClick={() => void confirm()}>{busy ? 'Naming…' : 'Confirm'}</button></div>
      : <div className="spq-dlg__foot"><button type="button" className="dlg-btn is-go" onClick={onClose}>Done</button></div>;
  return (
    <Modal open size="sm" title="Name your squad" className="fx spq-dlg" onClose={onClose} footer={foot}>
      <div className="dlg spq-dlg__body">
        {step === 'edit' && (<>
          <p className="spq-dlg__lead">The name is shown to all your teammates and on your invite poster. <b>It can only be set once.</b></p>
          <label className="spq-namein">
            <span className="sr-only">Squad name</span>
            <input value={raw} onChange={(e) => { setRaw(e.target.value.slice(0, 80)); setError(null); }} placeholder="e.g. Alpha Hunters" autoFocus maxLength={80} />
            <small className={`sx-num${count > NAME_MAX ? ' neg' : ''}`}>{count}/{NAME_MAX}</small>
          </label>
          <p className={`spq-dlg__hint${raw && !c.ok ? ' neg' : ''}`} role={raw && !c.ok ? 'alert' : undefined}>{raw && !c.ok ? c.error : 'Letters, numbers and spaces, 4 to 40 characters.'}</p>
          {error && <p className="spq-dlg__hint neg" role="alert">{error}</p>}
        </>)}
        {step === 'confirm' && c.ok && <p className="spq-dlg__lead">Name your squad <b>“{c.name}”</b>? SoDEX keeps it for good: it cannot be changed later.</p>}
        {step === 'done' && c.ok && <p className="spq-dlg__lead">Your squad is now <b>“{c.name}”</b>.</p>}
      </div>
    </Modal>
  );
}

/** The squad's details and members (owner: "get more info by clicking on it ... pop up for more info"). */
function SquadInfo({ v, which, name, cfg, list, onClose, onShare }: { v: PointsView; which: Which; name: string; cfg: BoostConfig; list: SquadList | null; onClose: () => void; onShare: () => void }) {
  const q = v.squad![which];
  const built = which === 'built' ? v.squad!.built : null;
  const own = useOwnCode(v.c.address);
  const code = which === 'built' && own.state === 'ok' ? own.code : null;
  const copy = async (text: string, what: string) => {
    try { await navigator.clipboard.writeText(text); notify('ok', `${what} copied.`); } catch { notify('warn', 'This browser did not allow copying.'); }
  };
  // You first, then by energy (SoDEX's own order).
  const members = list ? [...list.members].sort((a, b) => (a.role === 'self' ? -1 : b.role === 'self' ? 1 : b.energy - a.energy)) : null;
  return (
    <Modal open size="sm" title={name} className="fx spq-dlg" onClose={onClose}
      footer={<div className="spq-dlg__foot"><button type="button" className="dlg-btn" onClick={onShare}><Icon name="share" size={14} />Share</button><button type="button" className="dlg-btn is-go" onClick={onClose}>Done</button></div>}>
      <div className="dlg spq-dlg__body">
        <div className="spq-dlg__hero">
          <span className="spq-chip is-big"><Bolt size={16} /><b className="sx-num">{energy(q.volume)}</b><span>Squad Energy</span><EnergyInfo window={cfg.windowRounds} /></span>
          <span className={`spq-boost${q.pct ? '' : ' is-zero'}`}>{q.pct ? plusPct(q.pct) : 'No boost yet'}</span>
        </div>
        <dl className="spq-dlg__kv">
          <div><dt>Your part</dt><dd>{which === 'built' ? 'Captain: your invitees trade in it' : 'Teammate: you joined with its code'}</dd></div>
          {(list || built) && <div><dt>Members</dt><dd className="sx-num">{pts(list?.total ?? built!.members)}{built ? ` · ${pts(built.active)} active` : ''}</dd></div>}
          <div><dt>Volume, last {cfg.windowRounds} weeks</dt><dd className="sx-num">{money(q.volume)}</dd></div>
          <div><dt>Next step</dt><dd>{q.next ? `${plusPct(q.next.pct)} at ${energy(q.next.threshold)}, ${energy(q.next.missing)} to go` : 'Top step reached'}</dd></div>
        </dl>
        {members && members.length > 0 && (
          <div className="spq-members">
            <div className="spq-members__h"><span>Member</span><span>Energy</span></div>
            <ul>
              {members.map((m, i) => (
                <li key={`${m.address}${i}`} className={m.role === 'self' ? 'is-me' : undefined}>
                  <span className="spq-members__who"><b className="sx-num">{short(m.address)}</b><small>{ROLE_WORD[m.role]}</small></span>
                  <span className="sx-num">{energy(m.energy)}</span>
                </li>
              ))}
            </ul>
            {list!.truncated && <small className="spq-members__more">Showing the top {members.length} members by energy.</small>}
          </div>
        )}
        {code && (
          <div className="spq-dlg__code">
            <span><small>Invite code</small><b>{code}</b></span>
            <button type="button" className="spm-copy" onClick={() => void copy(code, 'Invite code')} aria-label="Copy invite code"><CopyIcon /></button>
            <span><small>Invite link</small><b className="is-link">{inviteLinkShown(code)}</b></span>
            <button type="button" className="spm-copy" onClick={() => void copy(inviteLink(code), 'Invite link')} aria-label="Copy invite link"><CopyIcon /></button>
          </div>
        )}
        <p className="spq-dlg__note">{v.squad!.fromSodex ? `SoDEX’s boost for you this week: ${plusPct(v.squad!.total)}, both squads together${v.squad!.earlyBird ? ', early bird included' : ''}.` : `Both squads together: ${plusPct(v.squad!.joined.pct + v.squad!.built.pct)}.`} Up to {plusPct(cfg.maxTotalBonusPct)} in all.</p>
      </div>
    </Modal>
  );
}
