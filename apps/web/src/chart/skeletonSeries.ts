/**
 * The loading skeleton's candles: the owner's reference chart, digitised.
 *
 * PROVENANCE. docs/skeleton-reference.png (836 x 614, a BTC 1m chart in this
 * app's own palette: up #00b481, down #ef4a3c, flat #c6b6ba, grid #272621 on a
 * #1a1a1a plot). Every candle was read back from its pixels:
 *
 *   - candle-coloured pixels collected per x column of the plot (x < 777,
 *     where the last-price badge starts), skipping row 577 - the dotted
 *     last-price rule, drawn in the down colour;
 *   - contiguous coloured columns grouped into candles: 96 groups, every one
 *     7 px wide (the newest clipped to 6 by the plot edge), centres from x=8
 *     to x=774 - a pitch of 8.063 px, each within 1 px of a uniform grid;
 *   - wick = the centre column's extent, body = the edge columns' extent,
 *     direction = the colour;
 *   - rows mapped to prices through the eleven horizontal gridlines (rows 24,
 *     78 ... 569 carry 85,300 ... 84,300, 54.5 px per 100). The fills cover
 *     rows [y(high), y(low)), so a lower edge's price is read one row below
 *     its last coloured row.
 *
 * Rounded to 0.1, a twentieth of a pixel row, so mapping these prices back
 * onto the reference frame (SKELETON_REF) reproduces the digitised rows.
 * The digitiser lives with the QA notes (chartqa/ref/digitise.mjs); rerun it
 * against a new reference to regenerate this table.
 *
 * Used by morph.ts (planSkeleton). Unit-tested in morph.test.ts.
 */

